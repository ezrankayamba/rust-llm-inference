"""Write crates/models/src/unicode_classes.rs: Unicode general categories as the DeepSeek V3
pre-tokenizer needs them (letters, marks, and punctuation or symbols), from Python's
unicodedata, and the letter class of DeepSeek LLM's pre-tokenizer.

usage: python scripts/gen_unicode_classes.py > crates/models/src/unicode_classes.rs
"""
import unicodedata as u

# The letters of DeepSeek LLM's pre-tokenizer (DeepSeek V2's tokenizer.json, its second Split:
# \s?[...]+), verbatim.
DEEPSEEK_LETTERS = "A-Za-zµÀ-ÖØ-öø-ƺƼ-ƿǄ-ʓʕ-ʯͰ-ͳͶͷͻ-ͽͿΆΈ-ΊΌΎ-ΡΣ-ϵϷ-ҁҊ-ԯԱ-ՖႠ-ჅᎠ-Ᏽᏸ-ᏽᲐ-ᲺᲽ-Ჿᴀ-ᴫᵫ-ᵷᵹ-ᶚḀ-ἕἘ-Ἕἠ-ὅὈ-Ὅὐ-ὗὙὛὝὟ-ώᾀ-ᾴᾶ-ᾼιῂ-ῄῆ-ῌῐ-ΐῖ-Ίῠ-Ῥῲ-ῴῶ-ῼℂℇℊ-ℓℕℙ-ℝℤΩℨK-ℭℯ-ℴℹℼ-ℿⅅ-ⅉⅎↃↄⰀ-ⱻⱾ-ⳤⳫ-ⳮⳲⳳꙀ-ꙭꚀ-ꚛꜢ-ꝯꝱ-ꞇꞋ-ꞎꭰ-ꮿﬀ-ﬆﬓ-ﬗＡ-Ｚａ-ｚ𐐀-𐑏𐒰-𐓓𐓘-𐓻𐲀-𐲲𐳀-𐳲𑢠-𑣟𞤀-𞥃"


def ranges(cls):
    out, i = [], 0
    while i < len(cls):
        if i + 2 < len(cls) and cls[i + 1] == "-":
            out.append((ord(cls[i]), ord(cls[i + 2])))
            i += 3
        else:
            out.append((ord(cls[i]), ord(cls[i])))
            i += 1
    return sorted(out)


CLASS = {"L": 1, "M": 2, "P": 3, "S": 3}
starts = []
prev = None
for cp in range(0x110000):
    c = CLASS.get(u.category(chr(cp))[0], 0)
    if c != prev:
        starts.append(cp << 2 | c)
        prev = c
print(f"""//! Generated by scripts/gen_unicode_classes.py from Unicode {u.unidata_version}: do not edit.

/// Each entry starts a run of code points of one class, `start << 2 | class`: 0 other, 1 letter
/// (L), 2 mark (M), 3 punctuation or symbol (P, S). Sorted, the first starting at 0.
#[rustfmt::skip]
pub(crate) const RUNS: [u32; {len(starts)}] = [""")
for i in range(0, len(starts), 10):
    print("    " + " ".join(f"0x{v:x}," for v in starts[i:i + 10]))
print("];")
letters = ranges(DEEPSEEK_LETTERS)
print(f"""
/// The letters of DeepSeek LLM's pre-tokenizer (`deepseek-llm`), inclusive ranges, sorted.
#[rustfmt::skip]
pub(crate) const DEEPSEEK_LETTERS: [(char, char); {len(letters)}] = [""")
for i in range(0, len(letters), 3):
    print("    " + " ".join(f"('\\u{{{a:x}}}', '\\u{{{b:x}}}')," for a, b in letters[i:i + 3]))
print("];")
